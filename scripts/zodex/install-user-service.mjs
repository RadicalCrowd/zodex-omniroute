#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import {
  chmodSync,
  cpSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SECRET_NAMES = [
  "JWT_SECRET",
  "API_KEY_SECRET",
  "STORAGE_ENCRYPTION_KEY",
  "MACHINE_ID_SALT",
  "OMNIROUTE_WS_BRIDGE_SECRET",
  "INITIAL_PASSWORD",
];

const REQUIRED_ARTIFACT_FILES = ["server-ws.mjs", "scripts/dev/run-standalone.mjs"];
const RUNTIME_ENV_NAMES = new Set([".env", ".env.local", "server.env"]);

function assertSingleLine(value, label) {
  if (typeof value !== "string" || value.length === 0 || /[\r\n\0]/.test(value)) {
    throw new Error(`${label} must be a non-empty single-line value`);
  }
  return value;
}

function assertReleaseId(value) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]{0,79}$/.test(value)) {
    throw new Error("release id must contain only letters, numbers, dot, underscore, or hyphen");
  }
  return value;
}

function ensureDirectory(directory, mode) {
  mkdirSync(directory, { recursive: true, mode });
  chmodSync(directory, mode);
}

function writeAtomic(filePath, content, mode) {
  ensureDirectory(path.dirname(filePath), 0o700);
  const temporaryPath = path.join(
    path.dirname(filePath),
    `.${path.basename(filePath)}.${process.pid}.${randomBytes(6).toString("hex")}.tmp`
  );
  writeFileSync(temporaryPath, content, { encoding: "utf8", mode });
  chmodSync(temporaryPath, mode);
  renameSync(temporaryPath, filePath);
  chmodSync(filePath, mode);
}

function parseEnvFile(content) {
  const values = new Map();
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const separator = trimmed.indexOf("=");
    if (separator < 1) continue;
    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }
  return values;
}

function quoteEnvValue(value) {
  return `"${assertSingleLine(value, "environment value")
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')}"`;
}

function createEnvironment(dataDir) {
  const values = new Map([
    ["NODE_ENV", "production"],
    ["PORT", "20128"],
    ["HOSTNAME", "127.0.0.1"],
    ["OMNIROUTE_SERVER_HOST", "127.0.0.1"],
    ["BASE_URL", "http://127.0.0.1:20128"],
    ["NEXT_PUBLIC_BASE_URL", "http://127.0.0.1:20128"],
    ["DATA_DIR", dataDir],
    ["REQUIRE_API_KEY", "true"],
    ["OMNIROUTE_BROKER_ONLY_MODE", "true"],
    ["OMNIROUTE_EMERGENCY_FALLBACK", "false"],
    ["APP_LOG_TO_FILE", "false"],
    ["AUTH_COOKIE_SECURE", "false"],
    ["STORAGE_ENCRYPTION_KEY_VERSION", "v1"],
  ]);
  for (const name of SECRET_NAMES) values.set(name, randomBytes(32).toString("hex"));

  return [
    "# Generated by the Zodex OmniRoute user-service installer.",
    "# Contains secrets. Never commit, paste into chat, or attach to bug reports.",
    ...[...values].map(([key, value]) => `${key}=${quoteEnvValue(value)}`),
    "",
  ].join("\n");
}

function validateEnvironment(envFile, expectedDataDir) {
  const mode = statSync(envFile).mode & 0o777;
  if (mode !== 0o600) throw new Error(`${envFile} must have mode 0600`);
  const values = parseEnvFile(readFileSync(envFile, "utf8"));
  const requiredValues = new Map([
    ["HOSTNAME", "127.0.0.1"],
    ["OMNIROUTE_SERVER_HOST", "127.0.0.1"],
    ["DATA_DIR", expectedDataDir],
    ["REQUIRE_API_KEY", "true"],
    ["OMNIROUTE_BROKER_ONLY_MODE", "true"],
    ["OMNIROUTE_EMERGENCY_FALLBACK", "false"],
  ]);
  for (const [name, expected] of requiredValues) {
    if (values.get(name) !== expected) {
      throw new Error(`${envFile} must set ${name}=${expected}`);
    }
  }
  for (const name of SECRET_NAMES) {
    if ((values.get(name) ?? "").length < 32) {
      throw new Error(`${envFile} must contain a strong ${name}`);
    }
  }
  return values;
}

function isRuntimeEnvArtifact(sourceRoot, candidate) {
  const relative = path.relative(sourceRoot, candidate);
  if (!relative || relative.startsWith("..")) return false;
  if (path.dirname(relative) !== ".") return false;
  const basename = path.basename(relative);
  return (
    RUNTIME_ENV_NAMES.has(basename) ||
    (basename.startsWith(".env.") && !basename.endsWith(".example"))
  );
}

function listRegularFiles(root, current = root, collected = []) {
  for (const name of readdirSync(current).sort()) {
    const filePath = path.join(current, name);
    const stats = lstatSync(filePath);
    if (stats.isDirectory()) listRegularFiles(root, filePath, collected);
    if (stats.isFile()) collected.push(path.relative(root, filePath));
  }
  return collected;
}

export function hashArtifactTree(root) {
  const aggregate = createHash("sha256");
  const files = listRegularFiles(root).sort((left, right) =>
    Buffer.compare(Buffer.from(`./${left}`), Buffer.from(`./${right}`))
  );
  for (const relative of files) {
    const fileHash = createHash("sha256")
      .update(readFileSync(path.join(root, relative)))
      .digest("hex");
    aggregate.update(`${fileHash}  ./${relative}\n`);
  }
  return aggregate.digest("hex");
}

function renderService({ appRoot, currentDir, dataDir, envFile, nodeBinary }) {
  const launcher = path.join(currentDir, "scripts/dev/run-standalone.mjs");
  const pathValue = (value) =>
    assertSingleLine(value, "systemd path")
      .replaceAll("\\", "\\x5c")
      .replaceAll(" ", "\\x20")
      .replaceAll("\t", "\\x09")
      .replaceAll('"', "\\x22")
      .replaceAll("'", "\\x27");
  const quoteArgument = (value) =>
    `"${assertSingleLine(value, "systemd argument").replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
  return `[Unit]
Description=Zodex OmniRoute OAuth broker
After=network-online.target
Wants=network-online.target
ConditionPathExists=${pathValue(launcher)}

[Service]
Type=simple
WorkingDirectory=${pathValue(currentDir)}
EnvironmentFile=${pathValue(envFile)}
ExecStart=${quoteArgument(nodeBinary)} ${quoteArgument(launcher)}
Restart=on-failure
RestartSec=5s
TimeoutStopSec=30s
KillSignal=SIGTERM
UMask=0077
NoNewPrivileges=true
PrivateTmp=true
PrivateDevices=true
ProtectSystem=strict
ProtectHome=read-only
ReadOnlyPaths=${pathValue(appRoot)}
ReadWritePaths=${pathValue(dataDir)}
ProtectHostname=true
ProtectClock=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectKernelLogs=true
ProtectControlGroups=true
RestrictNamespaces=true
RestrictRealtime=true
RestrictSUIDSGID=true
LockPersonality=true
SystemCallArchitectures=native
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=default.target
`;
}

function assertArtifact(artifactDir) {
  const resolved = path.resolve(artifactDir);
  if (!existsSync(resolved) || !statSync(resolved).isDirectory()) {
    throw new Error(`standalone artifact directory not found: ${resolved}`);
  }
  for (const relative of REQUIRED_ARTIFACT_FILES) {
    if (!existsSync(path.join(resolved, relative))) {
      throw new Error(`standalone artifact is missing ${relative}`);
    }
  }
  return resolved;
}

function resolveDefaultReleaseId(projectRoot) {
  try {
    return execFileSync("git", ["rev-parse", "--short=12", "HEAD"], {
      cwd: projectRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return `local-${Date.now()}`;
  }
}

export function installUserService(options = {}) {
  const homeDir = path.resolve(options.homeDir ?? os.homedir());
  const dataHome = path.resolve(options.dataHome ?? path.join(homeDir, ".local/share"));
  const configHome = path.resolve(options.configHome ?? path.join(homeDir, ".config"));
  const projectRoot = path.resolve(
    options.projectRoot ?? path.join(path.dirname(fileURLToPath(import.meta.url)), "../..")
  );
  const artifactDir = assertArtifact(
    options.artifactDir ?? path.join(projectRoot, ".build/next/standalone")
  );
  const nodeBinary = path.resolve(options.nodeBinary ?? process.execPath);
  if (!existsSync(nodeBinary) || !statSync(nodeBinary).isFile()) {
    throw new Error(`Node.js binary not found: ${nodeBinary}`);
  }
  const releaseId = assertReleaseId(options.releaseId ?? resolveDefaultReleaseId(projectRoot));

  const installRoot = path.resolve(options.installRoot ?? path.join(dataHome, "zodex-omniroute"));
  const appRoot = path.join(installRoot, "app");
  const releasesDir = path.join(appRoot, "releases");
  const releaseDir = path.join(releasesDir, releaseId);
  const currentDir = path.join(appRoot, "current");
  const dataDir = path.join(installRoot, "state");
  const zodexConfigDir = path.resolve(options.zodexConfigDir ?? path.join(configHome, "zodex"));
  const envFile = path.join(zodexConfigDir, "omniroute.env");
  const unitDir = path.resolve(options.unitDir ?? path.join(configHome, "systemd/user"));
  const unitFile = path.join(unitDir, "zodex-omniroute.service");

  ensureDirectory(installRoot, 0o700);
  ensureDirectory(appRoot, 0o700);
  ensureDirectory(releasesDir, 0o700);
  ensureDirectory(dataDir, 0o700);
  ensureDirectory(zodexConfigDir, 0o700);
  ensureDirectory(unitDir, 0o700);

  let environmentCreated = false;
  if (!existsSync(envFile)) {
    writeAtomic(envFile, createEnvironment(dataDir), 0o600);
    environmentCreated = true;
  }
  validateEnvironment(envFile, dataDir);

  let releaseCreated = false;
  if (!existsSync(releaseDir)) {
    const stagingDir = path.join(releasesDir, `.${releaseId}.${process.pid}.staging`);
    rmSync(stagingDir, { recursive: true, force: true });
    try {
      cpSync(artifactDir, stagingDir, {
        recursive: true,
        dereference: false,
        filter: (candidate) => !isRuntimeEnvArtifact(artifactDir, candidate),
      });
      for (const relative of REQUIRED_ARTIFACT_FILES) {
        if (!existsSync(path.join(stagingDir, relative))) {
          throw new Error(`copied release is missing ${relative}`);
        }
      }
      const manifest = {
        schemaVersion: 1,
        releaseId,
        sourceRevision: releaseId,
        artifactTreeSha256: hashArtifactTree(artifactDir),
        installedAt: new Date().toISOString(),
      };
      writeFileSync(
        path.join(stagingDir, "ZODEX_INSTALL_MANIFEST.json"),
        `${JSON.stringify(manifest, null, 2)}\n`,
        { encoding: "utf8", mode: 0o644 }
      );
      renameSync(stagingDir, releaseDir);
      releaseCreated = true;
    } catch (error) {
      rmSync(stagingDir, { recursive: true, force: true });
      throw error;
    }
  }

  const nextLink = path.join(appRoot, `.current.${process.pid}.${randomBytes(4).toString("hex")}`);
  symlinkSync(path.relative(appRoot, releaseDir), nextLink, "dir");
  renameSync(nextLink, currentDir);

  writeAtomic(
    unitFile,
    renderService({ appRoot, currentDir, dataDir, envFile, nodeBinary }),
    0o600
  );

  if (options.reloadSystemd === true) {
    execFileSync("systemctl", ["--user", "daemon-reload"], { stdio: "inherit" });
  }

  return {
    releaseId,
    releaseCreated,
    environmentCreated,
    artifactTreeSha256: JSON.parse(
      readFileSync(path.join(releaseDir, "ZODEX_INSTALL_MANIFEST.json"), "utf8")
    ).artifactTreeSha256,
    releaseDir,
    currentDir,
    dataDir,
    envFile,
    unitFile,
    enabledByInstaller: false,
    startedByInstaller: false,
  };
}

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--reload-systemd") {
      options.reloadSystemd = true;
      continue;
    }
    const key =
      argument === "--artifact"
        ? "artifactDir"
        : argument === "--node"
          ? "nodeBinary"
          : argument === "--release-id"
            ? "releaseId"
            : argument === "--install-root"
              ? "installRoot"
              : argument === "--config-root"
                ? "zodexConfigDir"
                : argument === "--unit-root"
                  ? "unitDir"
                  : null;
    if (!key) throw new Error(`unknown argument: ${argument}`);
    const value = argv[index + 1];
    if (!value) throw new Error(`${argument} requires a value`);
    options[key] = value;
    index += 1;
  }
  return options;
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  try {
    const result = installUserService(parseArgs(process.argv.slice(2)));
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`zodex-omniroute install failed: ${error.message}\n`);
    process.exitCode = 1;
  }
}
